#!/usr/bin/env node
// brand-kit.mjs — render a brand.json (from /webclone-brand) into:
//   <dir>/brand-kit.html   self-contained preview: logo, palette, type specimens, imagery, voice, layout
//   <dir>/theme.css        Tailwind v4 @theme + :root tokens ready to paste into globals.css
// and validate the brand.json shape.
//
// Usage: node scripts/brand-kit.mjs --brand <dir>/brand.json
// Part of the webclone plugin (MIT).

import fs from "node:fs";
import path from "node:path";

const ROLES = ["background", "surface", "foreground", "muted", "border", "accent", "accent-secondary"];

function fail(message) {
  console.error(`brand-kit: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  const out = { brand: "" };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--brand") out.brand = argv[++i] || "";
    else if (argv[i] === "--help" || argv[i] === "-h") out.help = true;
    else fail(`unexpected argument ${argv[i]}`);
  }
  return out;
}

const esc = (value) => String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

function validate(brand, dir) {
  const problems = [];
  if (!brand.name) problems.push("name is empty");
  const roles = new Map((brand.colors || []).map((c) => [c.role, c]));
  for (const role of ROLES) {
    const color = roles.get(role);
    if (!color) problems.push(`colors: missing role "${role}"`);
    else if (!/^#[0-9a-f]{6}$/i.test(color.hex || "")) problems.push(`colors.${role}: hex must be #rrggbb (got "${color.hex}")`);
  }
  for (const key of ["display", "body"]) if (!brand.typography?.[key]?.family) problems.push(`typography.${key}.family is empty`);
  const files = [brand.logo?.primary, ...(brand.logo?.alternates || []), ...(brand.imagery?.samples || []).map((s) => s.file)].filter(Boolean);
  for (const file of files) if (!fs.existsSync(path.join(dir, file))) problems.push(`file not found: ${file}`);
  if (!brand.logo?.primary) problems.push("logo.primary is empty (save the header SVG / icon into logos/)");
  return problems;
}

function contrast(hexA, hexB) {
  const lum = (hex) => {
    const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
  };
  const [a, b] = [lum(hexA), lum(hexB)].sort((x, y) => y - x);
  return Math.round(((a + 0.05) / (b + 0.05)) * 100) / 100;
}

function fontStack(spec) {
  if (!spec?.family) return "system-ui, sans-serif";
  return [`"${spec.family}"`, ...(spec.fallbacks || [])].join(", ");
}

function themeCss(brand) {
  const roles = new Map((brand.colors || []).map((c) => [c.role, c]));
  // A missing role must not leave an empty custom property; fall back and keep validation reporting it.
  const v = (role) => roles.get(role)?.hex || (role === "accent-secondary" ? "var(--brand-accent)" : "initial");
  const lines = [
    `/* ${brand.name} tokens generated by brand-kit.mjs from brand.json. Paste into src/app/globals.css. */`,
    ":root {",
    ...ROLES.map((role) => `  --brand-${role}: ${v(role)};`),
    `  --brand-font-display: ${fontStack(brand.typography?.display)};`,
    `  --brand-font-body: ${fontStack(brand.typography?.body)};`,
    `  --brand-font-mono: ${fontStack(brand.typography?.mono)};`,
    `  --brand-radius: ${brand.layout?.radius || "0px"};`,
    "}",
    "",
    "@theme inline {",
    "  --color-background: var(--brand-background);",
    "  --color-foreground: var(--brand-foreground);",
    "  --color-card: var(--brand-surface);",
    "  --color-card-foreground: var(--brand-foreground);",
    "  --color-muted: var(--brand-surface);",
    "  --color-muted-foreground: var(--brand-muted);",
    "  --color-border: var(--brand-border);",
    "  --color-primary: var(--brand-accent);",
    "  --color-primary-foreground: var(--brand-background);",
    "  --color-secondary: var(--brand-accent-secondary);",
    "  --color-ring: var(--brand-accent);",
    "  --font-heading: var(--brand-font-display);",
    "  --font-sans: var(--brand-font-body);",
    "  --font-mono: var(--brand-font-mono);",
    "  --radius: var(--brand-radius);",
    "}",
  ];
  const fonts = Object.values(brand.typography || {}).map((s) => s?.googleFontsUrl).filter(Boolean);
  if (fonts.length) lines.unshift(...fonts.map((url) => `/* Google Fonts stand-in: ${url} (prefer next/font/google with the same family) */`));
  return `${lines.join("\n")}\n`;
}

function html(brand) {
  const colors = brand.colors || [];
  const bg = colors.find((c) => c.role === "background")?.hex || "#ffffff";
  const fg = colors.find((c) => c.role === "foreground")?.hex || "#111111";
  const border = colors.find((c) => c.role === "border")?.hex || "#dddddd";
  const muted = colors.find((c) => c.role === "muted")?.hex || "#666666";
  const accent = colors.find((c) => c.role === "accent")?.hex || fg;
  const t = brand.typography || {};
  const fontLinks = Object.values(t).map((s) => s?.googleFontsUrl).filter(Boolean).map((u) => `<link rel="stylesheet" href="${esc(u)}">`).join("\n");
  const swatches = colors.map((c) => `
      <figure class="sw">
        <div class="chip" style="background:${esc(c.hex)}"></div>
        <figcaption><strong>${esc(c.name || c.role)}</strong><span>${esc(c.role)}</span><code>${esc(c.hex)}</code>${c.oklch ? `<code>${esc(c.oklch)}</code>` : ""}<em>${esc(c.usage || "")}</em><span class="ct">on bg ${contrast(c.hex, bg)}:1 · on fg ${contrast(c.hex, fg)}:1</span></figcaption>
      </figure>`).join("");
  const type = ["display", "body", "mono"].filter((k) => t[k]?.family).map((k) => `
      <div class="spec">
        <div class="ag" style="font-family:${esc(fontStack(t[k]))}">Ag</div>
        <div><strong>${esc(k)}</strong> · ${esc(t[k].family)}<br><span class="m">weights ${esc((t[k].weights || []).join(", "))}${t[k].notes ? ` · ${esc(t[k].notes)}` : ""}</span>
        <p style="font-family:${esc(fontStack(t[k]))}">${esc(brand.tagline || brand.name)}</p></div>
      </div>`).join("");
  const logos = [brand.logo?.primary, ...(brand.logo?.alternates || [])].filter(Boolean).map((f, i) => `<figure class="logo${i === 0 ? " primary" : ""}"><img src="${esc(f)}" alt="${esc(brand.name)} logo ${i + 1}"><figcaption>${i === 0 ? "primary" : "alternate"} · ${esc(f)}</figcaption></figure>`).join("");
  const imagery = (brand.imagery?.samples || []).map((s) => `<figure><img src="${esc(s.file)}" alt="${esc(s.caption || s.kind)}" loading="lazy"><figcaption>${esc(s.kind)} · ${esc(s.caption || "")}</figcaption></figure>`).join("");
  const list = (items) => (items || []).map((x) => `<li>${esc(x)}</li>`).join("");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(brand.name)} brand kit</title>
${fontLinks}
<style>
  :root { --bg:${bg}; --fg:${fg}; --border:${border}; --muted:${muted}; --accent:${accent}; }
  * { box-sizing: border-box; }
  body { margin:0; background:var(--bg); color:var(--fg); font:16px/1.55 ${fontStack(t.body)}; }
  main { max-width:1120px; margin:0 auto; padding:48px 20px 96px; }
  h1 { font:600 clamp(2.2rem,5vw,3.6rem)/1.05 ${fontStack(t.display)}; margin:0 0 8px; }
  h2 { font:600 1.25rem/1.2 ${fontStack(t.display)}; margin:56px 0 16px; padding-top:16px; border-top:1px solid var(--border); }
  .m, figcaption, em { color:var(--muted); font-size:.85rem; font-style:normal; }
  .grid { display:grid; gap:16px; grid-template-columns:repeat(auto-fill,minmax(200px,1fr)); }
  .sw .chip { height:96px; border-radius:${esc(brand.layout?.radius || "8px")}; border:1px solid var(--border); }
  .sw figcaption { display:flex; flex-direction:column; gap:2px; margin-top:8px; }
  code { font:12px/1.4 ${fontStack(t.mono)}; }
  .ct { font-size:.75rem; }
  .spec { display:flex; gap:24px; align-items:center; padding:16px 0; border-bottom:1px solid var(--border); }
  .ag { font-size:72px; line-height:1; min-width:120px; }
  .spec p { margin:6px 0 0; font-size:1.4rem; }
  .logo img { max-height:72px; max-width:100%; }
  .logo { padding:24px; border:1px solid var(--border); border-radius:8px; margin:0; }
  .imgs { display:grid; gap:12px; grid-template-columns:repeat(auto-fill,minmax(240px,1fr)); }
  .imgs img { width:100%; aspect-ratio:4/3; object-fit:cover; border-radius:6px; display:block; }
  figure { margin:0; }
  ul { padding-left:1.2em; }
  .btn { display:inline-block; padding:10px 18px; background:var(--accent); color:var(--bg); border-radius:${esc(brand.layout?.radius || "8px")}; text-decoration:none; }
</style>
</head>
<body>
<main>
  <p class="m">Brand kit · measured from <a href="${esc(brand.sourceUrl)}">${esc(brand.sourceUrl)}</a></p>
  <h1>${esc(brand.name)}</h1>
  <p>${esc(brand.tagline || "")}</p>
  <p class="m">${esc(brand.description || "")}</p>
  <p><a class="btn" href="#colors">Primary action</a></p>

  <h2>Logo</h2>
  <div class="grid">${logos || '<p class="m">No logo saved.</p>'}</div>
  ${brand.logo?.notes ? `<p class="m">${esc(brand.logo.notes)}</p>` : ""}

  <h2 id="colors">Color</h2>
  <div class="grid">${swatches}</div>

  <h2>Typography</h2>
  ${type}

  <h2>Imagery</h2>
  <p class="m">${esc(brand.imagery?.style || "")} ${esc(brand.imagery?.treatment || "")}</p>
  <div class="imgs">${imagery || '<p class="m">No imagery saved.</p>'}</div>

  <h2>Voice</h2>
  <p>${esc(brand.voice?.tone || "")}</p>
  <p class="m">${esc((brand.voice?.adjectives || []).join(" · "))}</p>
  <div class="grid"><div><strong>Use</strong><ul>${list(brand.voice?.vocabulary?.use)}</ul></div><div><strong>Avoid</strong><ul>${list(brand.voice?.vocabulary?.avoid)}</ul></div><div><strong>Pillars</strong><ul>${list(brand.voice?.messagingPillars)}</ul></div></div>

  <h2>Layout</h2>
  <p class="m">radius ${esc(brand.layout?.radius || "")} · border ${esc(brand.layout?.borderWeight || "")} · ${esc(brand.layout?.spacing || "")}</p>
  <ul>${list(brand.layout?.postureRules)}</ul>
</main>
</body>
</html>
`;
}

const args = parseArgs(process.argv.slice(2));
if (args.help || !args.brand) {
  console.log("Usage: node scripts/brand-kit.mjs --brand <dir>/brand.json\nWrites brand-kit.html and theme.css next to brand.json and reports schema problems.");
  process.exit(args.help ? 0 : 1);
}
const file = path.resolve(args.brand);
let brand;
try {
  brand = JSON.parse(fs.readFileSync(file, "utf8"));
} catch (error) {
  fail(`cannot read ${file}: ${error.message}`);
}
const dir = path.dirname(file);
fs.writeFileSync(path.join(dir, "brand-kit.html"), html(brand));
fs.writeFileSync(path.join(dir, "theme.css"), themeCss(brand));
const problems = validate(brand, dir);
console.log(`${path.join(dir, "brand-kit.html")}\n${path.join(dir, "theme.css")}`);
if (problems.length) {
  console.log(`⚠️ ${problems.length} problems:\n  - ${problems.join("\n  - ")}`);
  process.exitCode = 2;
} else {
  console.log("✅ brand.json complete");
}
