#!/usr/bin/env node
// Create (or reuse) a Next.js clone project for /webclone.
//
// Usage:
//   node scaffold.mjs <url1> [<url2> ...] [--cwd <dir>] [--dir <dir>] [--combined] [--install] [--force]
//
// Default: one project per origin, created at <cwd>/<site>-clone/.
//   --combined  put every origin into one project (named after the first URL)
//   --dir       explicit project directory (implies --combined)
//   --install   run `npm ci` (falls back to `npm install`) when node_modules is missing
//   --force     allow scaffolding into a non-empty directory that is not a webclone project
//
// If <cwd> (or --dir) is already a webclone project (.webclone.json present), it is reused.
// Prints a JSON summary on stdout; human notes go to stderr.

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SKILL_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATE_DIR = path.join(SKILL_DIR, "template");
const MARKER = ".webclone.json";
const SKIP = new Set(["node_modules", ".next", "out", "next-env.d.ts"]);

function fail(message, code = 1) {
  process.stderr.write(`webclone scaffold: ${message}\n`);
  process.exit(code);
}

function parseArgs(argv) {
  const opts = { urls: [], cwd: process.cwd(), dir: null, combined: false, install: false, force: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--cwd") opts.cwd = path.resolve(argv[++i] ?? fail("--cwd needs a value"));
    else if (arg === "--dir") opts.dir = path.resolve(argv[++i] ?? fail("--dir needs a value"));
    else if (arg === "--combined") opts.combined = true;
    else if (arg === "--install") opts.install = true;
    else if (arg === "--force") opts.force = true;
    else if (arg.startsWith("--")) fail(`unknown option ${arg}`);
    else opts.urls.push(arg);
  }
  if (opts.dir) opts.combined = true;
  return opts;
}

function normalizeUrl(raw) {
  let value = raw.trim().replace(/^<|>$/g, "").replace(/[,;]+$/, "");
  if (!/^[a-z][a-z0-9+.-]*:\/\//i.test(value)) value = `https://${value}`;
  let url;
  try {
    url = new URL(value);
  } catch {
    fail(`not a valid URL: ${raw}`);
  }
  if (!["http:", "https:"].includes(url.protocol)) fail(`only http(s) URLs are supported: ${raw}`);
  return url;
}

// stripe.com -> stripe-com, www.example.co.uk:8080 -> example-co-uk-8080
export function siteSlug(url) {
  const host = url.hostname.replace(/^www\./, "");
  const base = `${host}${url.port ? `-${url.port}` : ""}`;
  return base.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "site";
}

function pluginVersion() {
  try {
    return JSON.parse(fs.readFileSync(path.join(SKILL_DIR, "..", "..", ".claude-plugin", "plugin.json"), "utf8")).version;
  } catch {
    return "unknown";
  }
}

function readMarker(dir) {
  const file = path.join(dir, MARKER);
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return { sites: [] };
  }
}

function isEmptyDir(dir) {
  return !fs.existsSync(dir) || fs.readdirSync(dir).length === 0;
}

function copyTemplate(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (SKIP.has(entry.name) || entry.name.endsWith(".tsbuildinfo")) continue;
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyTemplate(from, to);
    else if (!fs.existsSync(to)) fs.copyFileSync(from, to);
  }
}

function personalizePackage(dir, name) {
  const file = path.join(dir, "package.json");
  const pkg = JSON.parse(fs.readFileSync(file, "utf8"));
  pkg.name = name;
  pkg.version = "0.1.0";
  pkg.description = "Website clone generated by /webclone";
  for (const key of ["author", "license", "repository", "homepage", "bugs", "keywords"]) delete pkg[key];
  fs.writeFileSync(file, `${JSON.stringify(pkg, null, 2)}\n`);

  const lockFile = path.join(dir, "package-lock.json");
  if (fs.existsSync(lockFile)) {
    const lock = JSON.parse(fs.readFileSync(lockFile, "utf8"));
    lock.name = name;
    lock.version = "0.1.0";
    if (lock.packages?.[""]) {
      lock.packages[""].name = name;
      lock.packages[""].version = "0.1.0";
      delete lock.packages[""].license;
    }
    fs.writeFileSync(lockFile, `${JSON.stringify(lock, null, 2)}\n`);
  }
}

function run(cmd, args, cwd) {
  // Args are fixed literals, so one shell string is safe and works for npm.cmd on Windows.
  const result = spawnSync([cmd, ...args].join(" "), { cwd, stdio: ["ignore", 2, 2], shell: true });
  return result.status === 0;
}

function installDeps(dir) {
  if (fs.existsSync(path.join(dir, "node_modules"))) return "present";
  process.stderr.write(`Installing dependencies in ${dir} ...\n`);
  // stdout must stay clean JSON, so npm output goes to stderr.
  const npmArgs = ["--no-audit", "--no-fund", "--loglevel=error"];
  const ok = run("npm", ["ci", ...npmArgs], dir) || run("npm", ["install", ...npmArgs], dir);
  return ok ? "installed" : "failed";
}

function prepareProject(dir, sites, opts) {
  const marker = readMarker(dir);
  let created = false;
  if (!marker) {
    if (!isEmptyDir(dir) && !opts.force) {
      fail(
        `${dir} exists, is not empty, and is not a webclone project. ` +
          "Ask the user before reusing it, then rerun with --force or choose another --dir.",
        3,
      );
    }
    copyTemplate(TEMPLATE_DIR, dir);
    personalizePackage(dir, path.basename(dir).toLowerCase().replace(/[^a-z0-9-]+/g, "-") || "webclone-site");
    created = true;
  }

  const known = new Map((marker?.sites ?? []).map((site) => [site.url, site]));
  for (const site of sites) if (!known.has(site.url)) known.set(site.url, site);
  const next = {
    generator: "webclone",
    templateVersion: marker?.templateVersion ?? pluginVersion(),
    createdAt: marker?.createdAt ?? new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    sites: [...known.values()],
  };
  fs.writeFileSync(path.join(dir, MARKER), `${JSON.stringify(next, null, 2)}\n`);

  for (const site of sites) {
    for (const sub of [`public/sites/${site.slug}`, `src/components/sites/${site.slug}`, `docs/research/${site.slug}`]) {
      fs.mkdirSync(path.join(dir, sub), { recursive: true });
    }
  }

  const install = opts.install ? installDeps(dir) : fs.existsSync(path.join(dir, "node_modules")) ? "present" : "skipped";
  return { projectDir: dir, created, reused: !created, install, sites };
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.urls.length === 0) fail("give at least one URL, e.g. node scaffold.mjs https://example.com", 2);
  if (!fs.existsSync(path.join(TEMPLATE_DIR, "package.json"))) fail(`template missing at ${TEMPLATE_DIR}`);

  const sites = opts.urls.map((raw) => {
    const url = normalizeUrl(raw);
    return { url: url.href, origin: url.origin, slug: siteSlug(url), pathname: url.pathname };
  });

  // Group by origin unless the user wants one combined app.
  const groups = new Map();
  for (const site of sites) {
    const key = opts.combined ? "all" : site.origin;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(site);
  }

  const cwdMarker = readMarker(opts.cwd);
  const projects = [];
  for (const groupSites of groups.values()) {
    let dir;
    if (opts.dir) dir = opts.dir;
    else if (cwdMarker && (groups.size === 1 || cwdMarker.sites?.some((s) => s.origin === groupSites[0].origin))) dir = opts.cwd;
    else dir = path.join(opts.cwd, `${groupSites[0].slug}-clone`);
    projects.push(prepareProject(dir, groupSites, opts));
  }

  process.stdout.write(`${JSON.stringify({ projects }, null, 2)}\n`);
  if (projects.some((p) => p.install === "failed")) process.exit(4);
}

main();
